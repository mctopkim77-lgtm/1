const { chromium } = require('playwright');
(async () => {
  const url = 'file:///home/user/1/tools/jpt-build/out.html';
  const b = await chromium.launch();
  const mk = async () => { const c = await b.newContext({ viewport: { width: 400, height: 800 } }); await c.grantPermissions(['clipboard-read', 'clipboard-write']).catch(() => {}); return c; };
  let fails = 0; const errs = [];
  const ok = (n, c, x) => { if (!c) fails++; console.log(c ? 'PASS' : 'FAIL', n, x === undefined ? '' : JSON.stringify(x)); };
  const A = await mk(), pa = await A.newPage(); pa.on('pageerror', e => errs.push(String(e)));
  await pa.goto(url + '#day-1'); await pa.waitForTimeout(300);
  await pa.locator('input[type=checkbox][data-k]').nth(0).check();
  const q = await pa.evaluate(() => DAYS[0].quiz[0].a);
  await pa.click('.q[data-qi="0"] .opt[data-o="' + ((q + 1) % 4) + '"]');
  await pa.click('.dbtn[data-day="-1"]'); await pa.click('[data-g="battle"]');
  await pa.click('[data-g="o' + await pa.evaluate(() => gv.ans) + '"]');
  const stA = await pa.evaluate(() => JSON.parse(localStorage.getItem('jpt14-v1')));
  await pa.goto(url); await pa.waitForTimeout(200);
  await pa.click('#syncout');
  const code = await pa.inputValue('#synccode');
  ok('code format', code.startsWith('JPT1.') && code.length > 50, code.slice(0, 20));
  await pa.waitForTimeout(300); ok('copy message', /복사/.test(await pa.textContent('#syncmsg')), await pa.textContent('#syncmsg'));
  const clip = await pa.evaluate(() => navigator.clipboard.readText()).catch(() => null);
  ok('clipboard has code', clip === null ? 'skipped' : clip === code, clip === null ? 'n/a' : undefined);
  // device B (empty)
  const B = await mk(), pb = await B.newPage(); pb.on('pageerror', e => errs.push(String(e)));
  await pb.goto(url); await pb.waitForTimeout(200);
  ok('B empty', await pb.evaluate(() => Object.keys(JSON.parse(localStorage.getItem('jpt14-v1') || '{"done":{}}').done).length) === 0);
  await pb.click('#syncin');
  ok('empty input -> error', /붙여넣은 뒤/.test(await pb.textContent('#syncmsg')));
  await pb.fill('#synccode', 'JPT1.garbage!!'); await pb.click('#syncin');
  ok('bad code rejected', /붙여넣은 뒤/.test(await pb.textContent('#syncmsg')));
  await pb.fill('#synccode', '  ' + code.slice(0, 40) + '\n' + code.slice(40) + ' '); // whitespace/newlines tolerated
  await pb.click('#syncin');
  ok('confirm step', /정말 덮어쓸까요/.test(await pb.textContent('#syncin')) && /가져올 기록/.test(await pb.textContent('#syncmsg')), await pb.textContent('#syncmsg'));
  const mid = await pb.evaluate(() => Object.keys(JSON.parse(localStorage.getItem('jpt14-v1') || '{"done":{}}').done).length);
  ok('not applied before confirm', mid === 0);
  await Promise.all([pb.waitForNavigation().catch(() => {}), pb.click('#syncin')]);
  await pb.waitForTimeout(600);
  const stB = await pb.evaluate(() => JSON.parse(localStorage.getItem('jpt14-v1')));
  ok('B equals A', JSON.stringify(stB) === JSON.stringify(stA), [Object.keys(stB.done), Object.keys(stB.wrong), stB.g && stB.g.xp]);
  ok('words w/ kanji intact', JSON.stringify(stB.words) === JSON.stringify(stA.words), Object.keys(stB.words || {}));
  await pb.goto(url + '#day-1'); await pb.waitForTimeout(300);
  ok('B checkbox shows', await pb.locator('input[type=checkbox][data-k]').nth(0).isChecked());
  await pb.screenshot({ path: process.argv[2] + '/sync-b.png' });
  await pb.goto(url); await pb.locator('#sync').scrollIntoViewIfNeeded();
  await pb.screenshot({ path: process.argv[2] + '/sync-ui.png' });
  ok('no h-scroll', await pb.evaluate(() => document.documentElement.scrollWidth) <= 400);
  ok('errors', errs.length === 0, errs);
  console.log(fails ? fails + ' FAILED' : 'ALL PASS');
  await b.close();
})();
